import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join, parse } from "node:path";
import { fileURLToPath } from "node:url";

const CHAPTER = /^\d{4}$/;
const readerDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = join(readerDir, "..", "source");
const outPath = join(readerDir, "src", "generated", "source-count.ts");

function chapterNumbers() {
  try {
    return readdirSync(sourceDir)
      .filter((name) => name.endsWith(".txt") && CHAPTER.test(parse(name).name))
      .map((name) => Number.parseInt(parse(name).name, 10))
      .filter((n) => Number.isInteger(n))
      .sort((a, b) => a - b);
  } catch (error) {
    if (error && error.code === "ENOENT") {
      return null;
    }
    throw error;
  }
}

const chapters = chapterNumbers();
if (!chapters || chapters.length === 0) {
  console.warn("source/ is missing or empty; leaving reader/src/generated/source-count.ts unchanged");
  process.exit(0);
}

const total = chapters.length;
const max = chapters[chapters.length - 1];
const contents = `/** Generated by \`npm run sync-source-count\`. Do not edit. */
export const SOURCE_CHAPTER_TOTAL = ${total};
export const SOURCE_CHAPTER_MAX = ${max};
`;

writeFileSync(outPath, contents);
console.log(`wrote ${total} source chapters (max ${max}) to src/generated/source-count.ts`);
